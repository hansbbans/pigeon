// Copies Allo (Josh Puckett, SIL Open Font License 1.1) into the Worker and the iOS app, pinned by release tag
// and checked against a SHA-256 so a moved tag cannot swap the font. Run after changing the tag:
// npm run vendor:allo
//
// Web: the "Friendly" variable font (weight 100-900, optical size automatic, roundness fixed at 50, half the size
// of the full variable font) plus the Regular oblique. iOS: static OTFs, because SwiftUI's Font.custom picks a
// face by PostScript name and does not synthesize bold or italic for a custom font.
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const TAG = 'v1.0.1';
const BASE = `https://raw.githubusercontent.com/joshpuckett/allo/${TAG}`;
const WEB_FONTS = {
	upright: { path: 'fonts/webfonts/AlloVariableFriendly.woff2', sha256: '28318fea1194f5bf077adf7fe3cece650d1230edf805bda7b203b7372893a6c2' },
	oblique: { path: 'fonts/webfonts/Allo-Oblique.woff2', sha256: '5a7e9779aa6a5e0dcac04794c2c3740ec017a35a4940e08eebd4ea2648837739' },
};
const IOS_FONTS = [
	{ path: 'fonts/otf/Allo-Regular.otf', sha256: 'c4a7d90aaf552d1897184da79977fdb7fb84fad223dccdee04f9d873237788f3' },
	{ path: 'fonts/otf/Allo-SemiBold.otf', sha256: '0b40bbcbd510de253c42ccc492e907e76f6a815b27d0e0624165ced6a513d02a' },
	{ path: 'fonts/otf/Allo-Bold.otf', sha256: '36e32b068ae532fc9f3ea2f6c8ab53512d10f926da5d57399afde2ab57b66e18' },
	{ path: 'fonts/otf/Allo-Oblique.otf', sha256: 'dfb432fe3e95fd29cac9e8225ac7133bf8c6b57c9400f91ae04f8b0e37283f67' },
	{ path: 'fonts/otf/Allo-BoldOblique.otf', sha256: 'b4c94eb306d61a59c48f416de51fba129dd8ddc1b353a19ff8f5d925bcd398d0' },
];
const LICENSE = { path: 'OFL.txt', sha256: 'abd0d6f604be7d1471efaa0bf89bca030d4a666437bfb507b85974d127902690' };
const IOS_FONTS_DIR = '../ios/PigeonReader/PigeonReader/Resources/Fonts/';

async function download(path) {
	const response = await fetch(`${BASE}/${path}`);
	if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
	return Buffer.from(await response.arrayBuffer());
}

async function verified(file) {
	const bytes = await download(file.path);
	const actual = createHash('sha256').update(bytes).digest('hex');
	if (actual !== file.sha256) throw new Error(`${file.path}: expected SHA-256 ${file.sha256}, got ${actual}`);
	return bytes;
}

const upright = await verified(WEB_FONTS.upright);
const oblique = await verified(WEB_FONTS.oblique);
const license = (await verified(LICENSE)).toString('utf8');
const version = TAG.slice(1);

writeFileSync(new URL('../docs/licenses/Allo-OFL.txt', import.meta.url), license);
writeFileSync(new URL(`${IOS_FONTS_DIR}Allo-OFL.txt`, import.meta.url), license);
for (const file of IOS_FONTS) {
	writeFileSync(new URL(`${IOS_FONTS_DIR}${file.path.split('/').pop()}`, import.meta.url), await verified(file));
}
writeFileSync(new URL('../src/browser-font-allo.ts', import.meta.url), `// Allo ${TAG} (Friendly variable upright and Regular oblique) from joshpuckett/allo, SIL Open Font License 1.1
// (docs/licenses/Allo-OFL.txt). Generated by scripts/vendor-allo.mjs; do not edit.
export const ALLO_VERSION = ${JSON.stringify(version)};
export const ALLO_PATH = ${JSON.stringify(`/app/fonts/allo-${version}.woff2`)};
export const ALLO_OBLIQUE_PATH = ${JSON.stringify(`/app/fonts/allo-oblique-${version}.woff2`)};
export const ALLO_WOFF2_BASE64 = ${JSON.stringify(upright.toString('base64'))};
export const ALLO_OBLIQUE_WOFF2_BASE64 = ${JSON.stringify(oblique.toString('base64'))};
`);
console.log(`Vendored Allo ${version} (${upright.length} + ${oblique.length} bytes woff2, ${IOS_FONTS.length} OTFs)`);
