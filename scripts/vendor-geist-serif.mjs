// Copies Geist Serif (Vercel, SIL Open Font License 1.1) into the Worker, pinned by release tag
// and checked against a SHA-256 so a moved tag cannot swap the font. Run after changing the tag:
// npm run vendor:geist-serif
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';

const TAG = 'v1.9.2';
const BASE = `https://raw.githubusercontent.com/vercel/geist-font/${TAG}`;
const WEB_FONT = { path: 'fonts/GeistSerif/webfonts/GeistSerif-Regular.woff2', sha256: '98979c19f111bc48d731702d40b8707845b667def7f722ee1b49346a75151dad' };

async function download(path) {
	const response = await fetch(`${BASE}/${path}`);
	if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
	return Buffer.from(await response.arrayBuffer());
}

function verified(bytes, { path, sha256 }) {
	const actual = createHash('sha256').update(bytes).digest('hex');
	if (actual !== sha256) throw new Error(`${path}: expected SHA-256 ${sha256}, got ${actual}`);
	return bytes;
}

const woff2 = verified(await download(WEB_FONT.path), WEB_FONT);
const license = (await download('OFL.txt')).toString('utf8');
const version = TAG.slice(1);

writeFileSync(new URL('../docs/licenses/GeistSerif-OFL.txt', import.meta.url), license);
writeFileSync(new URL('../src/browser-font-geist-serif.ts', import.meta.url), `// Geist Serif Regular from vercel/geist-font ${TAG}, SIL Open Font License 1.1
// (docs/licenses/GeistSerif-OFL.txt). Generated by scripts/vendor-geist-serif.mjs; do not edit.
export const GEIST_SERIF_VERSION = ${JSON.stringify(version)};
export const GEIST_SERIF_PATH = ${JSON.stringify(`/app/fonts/geist-serif-${version}.woff2`)};
export const GEIST_SERIF_WOFF2_BASE64 = ${JSON.stringify(woff2.toString('base64'))};
`);
console.log(`Vendored Geist Serif ${version} (${woff2.length} bytes woff2)`);
