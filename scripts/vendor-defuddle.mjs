// Copies the pinned Defuddle browser bundle into the iOS app and the Worker.
// Run after changing the defuddle version: npm run vendor:defuddle
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const bundlePath = require.resolve('defuddle');
if (!bundlePath.endsWith('/defuddle/dist/index.js')) throw new Error(`Unexpected Defuddle entry: ${bundlePath}`);
const source = readFileSync(bundlePath, 'utf8');
const { version } = JSON.parse(readFileSync(new URL('../package.json', `file://${bundlePath}`), 'utf8'));

writeFileSync(new URL('../ios/PigeonReader/PigeonReader/Resources/Defuddle.js', import.meta.url), source);
writeFileSync(new URL('../src/browser-defuddle-source.ts', import.meta.url), `// Defuddle ${version} by Steph Ango (kepano), MIT License. See
// ios/PigeonReader/PigeonReader/Resources/DEFUDDLE-NOTICE.md.
// Generated by scripts/vendor-defuddle.mjs from defuddle/dist/index.js; do not edit.
export const DEFUDDLE_VERSION = ${JSON.stringify(version)};
export const DEFUDDLE_SOURCE = ${JSON.stringify(source)};
`);
console.log(`Vendored Defuddle ${version} (${source.length} bytes)`);
